#!/usr/bin/env python3
"""Vol.5 · writes BLUEPRINT_SETTINGS.md: every setting with a default in the Blueprint's rag-server and ingestor-server
compose files at v2.6.2, quoted as written with its file and line, and what Vol.5 uses. Only three groups of settings
differ from the defaults (the embedding model, the answer model, and ingestion by bulk load instead of the ingestor);
every other row says "as shipped". Wiring (server addresses, ports, keys, user ids) is listed and marked as wiring.

usage: blueprint_settings_table.py --blueprint DIR --out FILE
"""
import argparse, hashlib, os, re

FILES = ("deploy/compose/docker-compose-rag-server.yaml", "deploy/compose/docker-compose-ingestor-server.yaml")
VAR = re.compile(r"^\s*-?\s*([A-Z0-9_]+)\s*[:=]\s*(\$\{([A-Z0-9_]+)(:?-)(.*)\})\s*(#.*)?$")
DEVIATION = {
    "APP_EMBEDDINGS_MODELNAME": "**deviation 1**: `nvidia/nemotron-3-embed-1b` (NIM 2.2.2, fp16), the encoder of Vol.4's whole-corpus vectors",
    "APP_LLM_MODELNAME": "**deviation 2**: `nvidia/nemotron-3-nano` (NIM 2.0.12, NVFP4); the default model needs several cards",
    "APP_QUERYREWRITER_MODELNAME": "follows deviation 2 (the query rewriter is off by default)",
    "APP_FILTEREXPRESSIONGENERATOR_MODELNAME": "follows deviation 2 (the filter generator is off by default)",
    "REFLECTION_LLM": "follows deviation 2 (reflection is off by default)",
    "SUMMARY_LLM": "follows deviation 2 (summaries are not used)",
}
WIRING = re.compile(r"(SERVERURL|SERVER_URL|_URL$|ENDPOINT|APIKEY|API_KEY|USERNAME|PASSWORD|_PORT$|PORT$|USERID|HOST|DOWNLOAD_LEGAL)")


def rows_of(path, rel):
    out = []
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        if line.lstrip().startswith("#"):
            continue
        m = VAR.match(line.rstrip("\n"))
        if not m:
            continue
        name, expr = m.group(1), m.group(2)
        out.append((name, expr, f"{rel}:{n}"))
    return out


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--blueprint", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    head = open(os.path.join(a.blueprint, ".git", "HEAD"), encoding="utf-8").read().strip() if os.path.isfile(os.path.join(a.blueprint, ".git", "HEAD")) else "?"
    prompt = os.path.join(a.blueprint, "src", "nvidia_rag", "rag_server", "prompt.yaml")
    psha = hashlib.sha256(open(prompt, "rb").read()).hexdigest()
    L = ["# The RAG Blueprint's settings, and what Vol.5 uses", "",
         "Source: `github.com/NVIDIA-AI-Blueprints/rag`, tag v2.6.2, commit `f20716d73ae69a544ad4a692f38d6178a64e6f36`. Every row is",
         "a setting with a default in the two compose files the volume runs, quoted as written (`${NAME:-default}`), with its",
         "file and line. Generated by `scripts/blueprint_settings_table.py`; edit the program, not this file.", "",
         "## The three deviations", "",
         "| # | What | Why |", "|---|---|---|",
         "| 1 | Embedding model: `nvidia/nemotron-3-embed-1b` (NIM 2.2.2, fp16) instead of `nvidia/llama-nemotron-embed-vl-1b-v2`, set through the Blueprint's own `APP_EMBEDDINGS_MODELNAME` (and its server address) | Vol.4's whole-corpus vectors were encoded with it (more than ten hours of encoding not repeated); it is the best of Vol.4's four embedding NIMs on the reduced MIRACL zh task |",
         "| 2 | Answer model: `nvidia/nemotron-3-nano` (NIM 2.0.12, NVFP4) instead of `nvidia/nemotron-3-super-120b-a12b`, through `APP_LLM_MODELNAME` | the default model needs at least two data-centre cards |",
         "| 3 | The whole corpora are bulk-loaded into the Blueprint's Elasticsearch index with the mapping the Blueprint's ingestor writes (read from a small collection it builds), instead of being sent through the ingestor | the ingestor would encode every passage again; Vol.4 holds the vectors |",
         "", "Everything else is as shipped. Two positive controls show the deviations change nothing else (query vectors of the Blueprint's query path against Vol.4's; a 100,000-passage slice loaded both ways).", "",
         "## Answering: what a question goes through, as shipped", "",
         "- Prompts: `src/nvidia_rag/rag_server/prompt.yaml` (SHA-256 `%s`), keys `chat_template` and `rag_template`; used unchanged." % psha,
         "- Reasoning: for Nemotron 3 Nano the Blueprint binds `chat_template_kwargs={\"enable_thinking\": <LLM_ENABLE_THINKING>}` (`src/nvidia_rag/utils/llm.py:276-277`); `LLM_ENABLE_THINKING` defaults to `true`, so reasoning is **on** as shipped. `LLM_LOW_EFFORT` is applied to other Nemotron 3 models only (`llm.py:303-305`). `FILTER_THINK_TOKENS` (default `true`) removes the reasoning from the answer the server returns.",
         "- Retrieval: `VECTOR_DB_TOPK` passages from the vector store, reranked, `APP_RETRIEVER_TOPK` of them sent to the model (both below).", ""]
    for f in FILES:
        rel = f
        L += [f"## `{os.path.basename(f)}`", "", "| Setting | As written | Where | Vol.5 |", "|---|---|---|---|"]
        for name, expr, where in rows_of(os.path.join(a.blueprint, f), rel):
            if name in DEVIATION:
                use = DEVIATION[name]
            elif "APP_LLM_MODELNAME" in expr:
                use = "follows deviation 2 through its nested default (the feature is off by default)"
            elif WIRING.search(name):
                use = "wiring (addresses, keys, ids): set to this host's containers"
            else:
                use = "as shipped"
            if "ingestor" in f and use == "as shipped":
                use = "as shipped where the ingestor runs (the two controls and the mapping); the whole corpora are bulk-loaded (deviation 3)"
            shown = expr.replace("|", chr(92) + "|")
            L.append(f"| `{name}` | `{shown}` | `{where}` | {use} |")
        L.append("")
    open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print(a.out, sum(1 for l in L if l.startswith("| `")), "rows")


if __name__ == "__main__":
    main()
