#!/usr/bin/env python3
"""Third directory rename (2026-10-05): vol3-judges/ -> vol3-guardrails/. Input: tools/renumber_map_3.json.

This file runs tools/renumber_dirs.py; it does not replace it. That program is bound by SHA-256 in frozen
pre-registrations and is not edited, and it reads two map files by name. Here it is loaded as a module, the third map is
added to its list, the values it derives from the maps when it starts are derived again, and its own phases are called:
rename, docs, verify, move-untracked, check-old-dirs, pathmap, with the arguments it documents.

Two things are added to what it writes into PATH_MAP.md and PATH_MAP.json:
  notes    the paragraphs of `path_map_notes` in the map, placed under the volume table. They name the commit at which
           the paths of a column exist.
  checks   `anchor_checks` in the map: before anything is written, every path of the named column must exist in the
           tree of the named commit, and that commit must be an ancestor of the rename commit. Exit 4 if not.

The gate `renumber_dirs.py check-old-dirs` knows the old names of the first two renames only. This file's
`check-old-dirs` refuses those and `vol3-judges` as well.

usage: renumber_dirs_gen3.py rename | docs [--no-commit] | verify --report FILE [--clones] | move-untracked
                             | check-old-dirs | pathmap
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
MAP_3 = "renumber_map_3.json"
if "--gen" in sys.argv:
    sys.exit("refused: this file works on the third rename only (no --gen)")
import renumber_dirs as R  # noqa: E402

R.MAP_FILES = list(R.MAP_FILES) + [MAP_3]
R.MAPS = list(R.MAPS) + [json.load(open(os.path.join(HERE, MAP_3), encoding="utf-8"))]
R.GEN = len(R.MAPS)
R.MAP = R.MAPS[-1]
R.MOVES = [(m["from"], m["to"]) for m in R.MAP["moves"]]
R.OLD, R.NEW = R.MAP["old_roots"], R.MAP["new_roots"]
R.ALL_OLD = [o for m in R.MAPS for o in m["old_roots"]]
R.HISTORY_FILES = set(R.MAP.get("history_files", []))
R.BEFORE = os.path.join(R.GITDIR, f"renumber_before_g{R.GEN}.json")
R.SUBJECTS = ["Rename the volume directories to match the volume numbers (moves only)"] + [m["subject"] for m in R.MAPS[1:]]
R.RENAME_SUBJECT = R.SUBJECTS[-1]
R.PATH_TOKEN = re.compile(r"(?<![\w.-])(" + "|".join(re.escape(o) for o in sorted(R.OLD, key=len, reverse=True)) + r")/")
R.RUN_CODES = R.MAP.get("run_codes", {})
R.RUN_CODE = re.compile(r"^(" + "|".join(re.escape(o) for o in R.OLD) + r")/(results|scripts)/((?:run_)?(p\d+)(?:[_./]|$).*)$")
assert R.GEN == 3 and R.OLD == ["vol3-judges"] and R.NEW == ["vol3-guardrails"], (R.GEN, R.OLD, R.NEW)

_chain = R.path_map_files_chain


def anchor_checks(chain_rows, rename_commit):
    out = []
    for a in R.MAP.get("anchor_checks", []):
        tree = set(R.z(R.git("ls-tree", "-r", "-z", "--name-only", a["commit"])))
        paths = [r[a["column"]] for r in chain_rows if r[a["column"]]]
        missing = [p for p in paths if p not in tree]
        ancestor = subprocess.run(["git", "-C", R.ROOT, "merge-base", "--is-ancestor", a["commit"], rename_commit]).returncode == 0
        out.append({"commit": a["commit"], "column": a["column"], "paths": len(paths), "missing": len(missing), "ancestor_of_the_rename_commit": ancestor})
        if missing or not ancestor or not paths:
            print(json.dumps(out, indent=1)); sys.exit(4)
    return out


def chain_with_notes():
    js, md, rows = _chain()
    d = json.loads(js)
    cols = d["columns"]
    d["anchor_checks"] = anchor_checks([[r[c] for c in cols] for r in d["chain"]], R.rename_commit())
    d["notes"] = R.MAP.get("path_map_notes", [])
    d = {k: d[k] for k in ("generated_by", "generations", "columns", "rows", "notes", "anchor_checks", "chain")}
    lines = md.split("\n")
    at = next(i for i, l in enumerate(lines) if l.startswith("Generated by `tools/renumber_dirs.py`"))
    notes = []
    for n in d["notes"]:
        notes += [n, ""]
    lines[at] = lines[at].replace("Generated by `tools/renumber_dirs.py`", "Generated by `tools/renumber_dirs.py` (run through `tools/renumber_dirs_gen3.py`)", 1)
    return json.dumps(d, indent=1, ensure_ascii=False) + "\n", "\n".join(lines[:at] + notes + lines[at:]), rows


R.path_map_files_chain = chain_with_notes

if __name__ == "__main__":
    raise SystemExit(R.main())
