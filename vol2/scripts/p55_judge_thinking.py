#!/usr/bin/env python3
"""Vol.2 · can Nemotron 3 Nano (A2) act as the self-check judge once its reasoning is switched off? Two layers, one
container, so that "the model cannot" and "Guardrails does not pass the switch" are told apart.

Why: in results/p53_guardrails/ both Nemotron judges answered the self-check prompts with reasoning and the rail blocked
every question; a /no_think system message fixed Nemotron Nano 9B v2 and did nothing for Nemotron 3 Nano. The model card
and the NIM API reference name a different switch for Nemotron 3: chat_template_kwargs {"enable_thinking": false}.

Container: A2 as in p53_guardrails (NIM_MAX_MODEL_LEN 8192, --max-num-seqs 32), then an adaptive warm-up (A2 serves at
roughly half speed for a variable 10-50 s after READY): discarded ~1k-token requests until at least 60 s and 6 requests
have passed and the last three generation rates agree within 5% and are all >= 220 tok/s, capped at 25 requests / 300 s.

L1 · direct to the NIM, no Guardrails. Per E3 question and round, five calls, 0.5 s apart:
  IN_T  the Vol.1 self_check_input prompt (benchmark/guardrails/config.yml, {{ user_input }} filled), no switch  -> control
  IN_F  the same prompt with chat_template_kwargs {"enable_thinking": false}
  ANS   the Vol.1 E3 nim-only request (the answer the output check needs; its text is used and discarded)
  OUT_F the self_check_output prompt ({{ bot_response }} = ANS) with the switch
  OUT_T the same without the switch                                                                              -> control
  Judge calls use exactly what Guardrails 0.23.0 sends: non-streamed, temperature 0.001 (RailsConfig.lowest_temperature),
  top_p 0.9, max_tokens 1024. Recorded per call: HTTP status (and the NIM's error text verbatim if it refuses the field),
  completion tokens, duration, finish_reason, the first word of the reply as a label (yes / no / other), and the reply's
  SHA-256 and length. No reply text is stored.
L2 · through NeMo Guardrails 0.23.0. Arm J = Vol.1's rail config (model name substituted, top_p 0.9 added, as in
  p53_guardrails) plus two task-typed models, self_check_input and self_check_output, identical to the main model but for
  parameters.chat_template_kwargs {"enable_thinking": false}. Guardrails 0.23.0 passes unknown model parameters into the
  request body (nemoguardrails/llm/models/openai_chat.py:83 merges them, llm/clients/openai_compatible.py:48
  payload.update) and gives a self-check action the task-typed model when one exists (colang/v1_0/runtime/runtime.py:
  644-645), so only the two judge calls change; the answer is generated by the main model with reasoning on, as in N.
  Arms N (nim-only, the Vol.1 E3 payload) and J rotated per question, 45 questions x 3 rounds, 2 s apart, one warm-up
  request per arm excluded. Per rail row the judge calls from rails.explain(); each judge reply's first 200 characters
  are reduced to a first-word label, SHA-256 and length before anything is written.
usage: p55_judge_thinking.py --out DIR --gr023-py PYTHON [--rounds 3] [--question-limit 0] [--layers L1,L2]
env: NGC_ENV_FILE (passed to --env-file, never read) · NIM_CACHE_DIR
"""
import argparse, hashlib, json, os, re, sys, time

import requests
import yaml

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "vol1b", "scripts"))
from p50_footprint import ARMS, BASE, docker_logs, gpu, metrics_cache_config, now, sh, start, stop  # noqa: E402
from p53_longctx import QFILE, build_prompt, request as ctx_request  # noqa: E402
from p53_guardrails import GR_ENV, rail_config_for  # noqa: E402
from bridge_2x2 import COOLDOWN, QUESTIONS, QUESTIONS_SHA, RAIL_CONFIG, TOP_P, Worker, nim_only, sha  # noqa: E402

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
SWITCH = {"enable_thinking": False}
JUDGE_PARAMS = {"temperature": 0.001, "top_p": TOP_P, "max_tokens": 1024}
WARM = {"min_s": 60, "min_n": 6, "tol": 0.05, "fast": 220.0, "max_n": 25, "max_s": 300}
h = lambda s: hashlib.sha256((s or "").encode("utf-8")).hexdigest()


def first_word(text):
    m = re.search(r"[A-Za-z]+", text or "")
    w = m.group(0).lower() if m else ""
    return w if w in ("yes", "no") else "other"


def judge(model, prompt, switch):
    payload = {"model": model, "messages": [{"role": "user", "content": prompt}], "stream": False, **JUDGE_PARAMS}
    if switch:
        payload["chat_template_kwargs"] = dict(SWITCH)
    t0 = time.perf_counter()
    try:
        r = requests.post(BASE + "/v1/chat/completions", json=payload, timeout=300)
    except Exception as e:
        return {"error": str(e)[:300], "duration_ms": round((time.perf_counter() - t0) * 1000, 1)}
    dur = round((time.perf_counter() - t0) * 1000, 1)
    if r.status_code != 200:
        return {"http_status": r.status_code, "error_text": r.text[:600], "duration_ms": dur}
    d = r.json(); ch = (d.get("choices") or [{}])[0]; msg = ch.get("message") or {}
    content = msg.get("content") or ""
    reasoning = msg.get("reasoning_content") or msg.get("reasoning") or ""
    return {"http_status": 200, "duration_ms": dur, "completion_tokens": (d.get("usage") or {}).get("completion_tokens"),
            "prompt_tokens": (d.get("usage") or {}).get("prompt_tokens"), "finish_reason": ch.get("finish_reason"),
            "label": first_word(content), "content_sha256": h(content), "content_chars": len(content),
            "reasoning_field_chars": len(reasoning), "content_empty": content.strip() == ""}


def j_config(model, out_dir):
    """Vol.1 rail config with the model substituted and top_p added (p53_guardrails.rail_config_for), plus the two
    task-typed judge models carrying the switch. Written to out_dir/config.yml; returns (path, the added entries)."""
    base_path, substituted = rail_config_for(model, out_dir, RAIL_CONFIG)
    cfg = yaml.safe_load(open(base_path, encoding="utf-8"))
    main = next(m for m in cfg["models"] if m.get("type") == "main")
    added = []
    for task in ("self_check_input", "self_check_output"):
        m = {"type": task, "engine": main["engine"], "model": main["model"], "parameters": dict(main.get("parameters") or {})}
        m["parameters"]["chat_template_kwargs"] = dict(SWITCH)
        cfg["models"].append(m); added.append(m)
    text = ("# Vol.2 P55 G2 arm J: Vol.1 rail config (model name substituted, top_p added) plus two task-typed judge models\n"
            "# whose only difference from the main model is chat_template_kwargs.enable_thinking = false.\n")
    text += yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True)
    open(base_path, "w", encoding="utf-8", newline="\n").write(text)
    return base_path, substituted, added


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True); ap.add_argument("--gr023-py", required=True)
    ap.add_argument("--rounds", type=int, default=3); ap.add_argument("--question-limit", type=int, default=0)
    ap.add_argument("--layers", default="L1,L2"); ap.add_argument("--test", action="store_true")
    a = ap.parse_args()
    layers = a.layers.split(",")
    os.makedirs(a.out, exist_ok=True); logdir = os.path.join(a.out, "logs"); os.makedirs(logdir, exist_ok=True)
    if sha(QUESTIONS) != QUESTIONS_SHA:
        sys.exit("e3_questions.json sha256 mismatch")
    qs = json.load(open(QUESTIONS, encoding="utf-8"))
    if a.question_limit:
        qs = qs[:a.question_limit]
    vcfg = yaml.safe_load(open(RAIL_CONFIG, encoding="utf-8"))
    tmpl = {p["task"]: p["content"] for p in vcfg["prompts"]}
    bank = json.load(open(QFILE, encoding="utf-8"))
    if sh(["docker", "ps", "-q"], timeout=30).stdout.strip():
        sys.exit("refused: a container is running")
    l1 = open(os.path.join(a.out, "l1_calls.jsonl"), "a", encoding="utf-8", newline="\n")
    rows_f = open(os.path.join(a.out, "rows_public.jsonl"), "a", encoding="utf-8", newline="\n")
    ev = open(os.path.join(a.out, "events.jsonl"), "a", encoding="utf-8", newline="\n")

    def event(**kw):
        kw["at"] = now(); ev.write(json.dumps(kw, ensure_ascii=False) + "\n"); ev.flush()
        print("  event", {k: kw[k] for k in kw if k in ("kind", "layer", "at")}, flush=True)

    arm = "A2"
    ARMS[arm] = dict(ARMS[arm], env=GR_ENV[arm])
    name = "p55-judge-a2"
    before = gpu()
    st_ = start(arm, name, None, logdir)
    if not st_["ready"]:
        event(kind="container_failed", reason=st_.get("reason"), log_lines=st_.get("log_lines")); stop(name); return 1
    time.sleep(5)
    model = requests.get(BASE + "/v1/models", timeout=30).json()["data"][0]["id"]
    event(kind="container_start", image=ARMS[arm]["image"], profile=ARMS[arm]["profile"], env=st_["env"], served_model=model,
          gpu_before_launch=before, gpu_ready=gpu(), seconds_to_ready=st_["seconds_to_ready"], cache_config=metrics_cache_config(),
          log_lines=st_["log_lines"], templates_sha256={k: h(v) for k, v in tmpl.items()}, judge_params=JUDGE_PARAMS, switch=SWITCH,
          questions={"file": "benchmark/e3_questions.json", "sha256": QUESTIONS_SHA, "n": len(qs)}, rounds=a.rounds)

    # adaptive warm-up
    t_w = time.time(); k = 0; rates = []; stable = False
    wmin_s, wmin_n, wmax_n = (10, 2, 6) if a.test else (WARM["min_s"], WARM["min_n"], WARM["max_n"])
    while True:
        r = ctx_request(model, build_prompt(bank, 1024, 1000 + 7 * k)); rates.append(r.get("generation_tps")); k += 1
        last3 = [x for x in rates[-3:] if isinstance(x, (int, float))]
        stable = len(last3) == 3 and (max(last3) - min(last3)) / max(last3) <= WARM["tol"] and min(last3) >= WARM["fast"]
        el = time.time() - t_w
        if (el >= wmin_s and k >= wmin_n and stable) or k >= wmax_n or el >= WARM["max_s"]:
            break
        time.sleep(1)
    event(kind="warmup_end", requests=k, seconds=round(time.time() - t_w, 1), stabilized=stable, rates=rates)

    if "L1" in layers:
        event(kind="layer_start", layer="L1")
        for rnd in range(1, a.rounds + 1):
            for q in qs:
                base = {"question_id": q["id"], "category": q["category"], "expected_action": q["expected_action"], "round": rnd}
                p_in = tmpl["self_check_input"].replace("{{ user_input }}", q["text"])
                for cond, sw in (("IN_T", False), ("IN_F", True)):
                    rec = judge(model, p_in, sw); rec.update(base, cond=cond, t=now())
                    l1.write(json.dumps(rec, ensure_ascii=False) + "\n"); l1.flush(); time.sleep(0.5)
                ans = nim_only(BASE, model, q["text"]); full = ans.pop("response_full", "") or ""
                l1.write(json.dumps({**base, "cond": "ANS", "t": now(), "http_status": ans.get("http_status"), "error": ans.get("error"),
                                     "total_latency_ms": ans.get("total_latency_ms"), "usage": ans.get("usage"), "finish_reason": ans.get("finish_reason"),
                                     "content_sha256": h(full), "content_chars": len(full)}, ensure_ascii=False) + "\n"); l1.flush(); time.sleep(0.5)
                p_out = tmpl["self_check_output"].replace("{{ bot_response }}", full)
                for cond, sw in (("OUT_F", True), ("OUT_T", False)):
                    rec = judge(model, p_out, sw); rec.update(base, cond=cond, t=now())
                    l1.write(json.dumps(rec, ensure_ascii=False) + "\n"); l1.flush(); time.sleep(0.5)
            print(f"  L1 round {rnd} done · {now()}", flush=True)
        event(kind="layer_end", layer="L1")

    if "L2" in layers:
        cfg_dir = os.path.join(a.out, "gr_config_a2_j")
        cfg_path, substituted, added = j_config(model, cfg_dir)
        worker = None; werr = None
        try:
            worker = Worker("J", a.gr023_py, cfg_dir, os.path.join(logdir, "worker_a2_j_gr023.stderr.txt"))
        except Exception as e:
            werr = str(e)[:800]
        event(kind="layer_start", layer="L2", rail_config={"source": "benchmark/guardrails/config.yml", "source_sha256": sha(RAIL_CONFIG), "used_sha256": sha(cfg_path),
              "model_name_substitution": substituted, "added_top_p": TOP_P, "added_task_models": added}, worker_versions=getattr(worker, "versions", None), worker_error=werr)

        def one(req_arm, q, rnd, warmup=False):
            if req_arm == "N":
                r = nim_only(BASE, model, q["text"])
            elif worker is None:
                r = {"error": "guardrails worker unavailable: " + str(werr)}
            else:
                r = worker.ask(f"{q['id']}#{rnd}", q["text"])
            r.pop("key", None)
            full = r.pop("response_full", None)
            r["response_sha256"] = h(full) if full is not None else None
            r["response_chars"] = len(full) if full is not None else None
            for c in r.get("llm_calls") or []:
                if "completion_head" in c:
                    head = c.pop("completion_head") or ""
                    c["completion_head_label"] = first_word(head); c["completion_head_sha256"] = h(head); c["completion_head_chars"] = len(head)
            r.update({"arm": arm, "request_arm": req_arm, "question_id": q["id"], "category": q["category"], "expected_action": q["expected_action"],
                      "round": rnd, "warmup": warmup, "t": now(), "docker_ps_before": sh(["docker", "ps", "--format", "{{.Names}}"], timeout=30).stdout.split()})
            rows_f.write(json.dumps(r, ensure_ascii=False) + "\n"); rows_f.flush()
            time.sleep(COOLDOWN)
            return r

        for req_arm in ("N", "J"):
            one(req_arm, qs[0], 0, warmup=True)
        for rnd in range(1, a.rounds + 1):
            for q in qs:
                for req_arm in ("N", "J"):
                    r = one(req_arm, q, rnd)
                    if "error" in r:
                        print(f"  ERROR {req_arm} {q['id']} r{rnd}: {str(r['error'])[:140]}", flush=True)
            print(f"  L2 round {rnd} done · {now()}", flush=True)
        if worker is not None:
            worker.close()
        event(kind="layer_end", layer="L2")

    L = docker_logs(name)
    open(os.path.join(logdir, f"{name}.container.log.txt"), "w", encoding="utf-8", newline="\n", errors="replace").write("\n".join(l for l in L.splitlines() if "nvapi" not in l.lower()) + "\n")
    stop(name)
    event(kind="container_end", gpu_after_stop=gpu())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
